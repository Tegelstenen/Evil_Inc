"use client";

import { useEffect, useState } from "react";

import { Button } from "@/components/ui/button";
import { Orb } from "@/features/conversation/components/orb";

// Example usage component
const ConversationPage = () => {
	const [isActive, setIsActive] = useState(false);
	const [isTalking, setIsTalking] = useState(false);
	const [talkingIntensity, setTalkingIntensity] = useState(0);

	useEffect(() => {
		console.log("isTalking changed:", isTalking); // Debug log
		let startTime = Date.now() / 1000;
		let animationFrameId: number;

		const updateIntensity = () => {
			const currentTime = Date.now() / 1000;
			const elapsedTime = currentTime - startTime;

			// Scale the elapsed time to match our time array range
			const scaledTime = elapsedTime + time[0]; // Add the offset to start from the first time value

			// Find the two closest time points for interpolation
			const nextIndex = time.findIndex((t) => t > scaledTime);

			if (nextIndex === -1) {
				console.log("Reached end of sequence"); // Debug log
				setTalkingIntensity(intensity[intensity.length - 1]);
				setIsTalking(false);
				return;
			}

			if (nextIndex === 0) {
				// Before first time point, use first intensity
				setTalkingIntensity(intensity[0]);
			} else {
				// Interpolate between the two closest points
				const prevTime = time[nextIndex - 1];
				const nextTime = time[nextIndex];
				const prevIntensity = intensity[nextIndex - 1];
				const nextIntensity = intensity[nextIndex];

				// Calculate interpolation factor (0 to 1)
				const t = (scaledTime - prevTime) / (nextTime - prevTime);

				// Linear interpolation between intensities
				const interpolatedIntensity =
					prevIntensity + t * (nextIntensity - prevIntensity);
				setTalkingIntensity(interpolatedIntensity);
			}

			animationFrameId = requestAnimationFrame(updateIntensity);
		};

		if (isTalking) {
			startTime = Date.now() / 1000;
			updateIntensity();
		} else {
			setTalkingIntensity(0);
		}

		return () => {
			if (animationFrameId) {
				cancelAnimationFrame(animationFrameId);
			}
		};
	}, [isTalking]);

	return (
		<div className="flex min-h-screen w-full flex-col justify-center">
			<Orb
				isActive={isActive}
				isTalking={isTalking}
				talkingIntensity={talkingIntensity}
			/>
			<div className="mt-4 flex gap-4">
				<Button
					onClick={() => {
						setIsActive(!isActive);
					}}
					className="border border-white bg-black text-white hover:bg-gray-800"
				>
					{isActive ? "Deactivate" : "Activate"}
				</Button>
				<Button
					onClick={() => {
						setIsTalking(!isTalking);
					}}
					disabled={!isActive}
					className="border border-white bg-black text-white hover:bg-gray-800 disabled:opacity-50"
				>
					{isTalking ? "Stop Talking" : "Simulate Talking"}
				</Button>
			</div>
		</div>
	);
};

export default ConversationPage;

